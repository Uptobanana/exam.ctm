def find_content_boundaries(text, point_id):
    id_pattern = f"id:'{point_id}'"
    idx = text.find(id_pattern)
    if idx == -1:
        raise ValueError(f"ID {point_id} not found")
    content_marker = "content:'"
    content_idx = text.find(content_marker, idx)
    if content_idx == -1:
        raise ValueError(f"content marker not found after {point_id}")
    start = content_idx + len(content_marker)
    i = start
    while i < len(text):
        if text[i] == "'":
            rest = text[i+1:i+5]
            if rest.startswith('}') or rest.startswith(','):
                return start, i
        i += 1
    raise ValueError(f"Could not find closing quote for {point_id}")

def replace_content(text, point_id, new_content):
    start, end = find_content_boundaries(text, point_id)
    return text[:start] + new_content + text[end:]

